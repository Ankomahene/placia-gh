export const LEAVES: CategoryLeaf[] = TAXONOMY.flatMap((g) => g.children);

/** Overture category → leaf slug, built once. */
export const OVERTURE_TO_LEAF = new Map<string, string>([
  ...LEAVES.flatMap((l) => l.overture.map((c) => [c, l.slug] as const)),
  ...Object.entries(OVERTURE_EXTRA).flatMap(([slug, cats]) => cats.map((c) => [c, slug] as const)),
]);

/** Pick the most specific Overture category we know: primary, then hierarchy (deepest first), then basic. */
export function overtureLeaf(
  primary: string | null,
  hierarchy: readonly string[] | null,
  basic: string | null,
) {
  for (const c of [primary, ...[...(hierarchy ?? [])].reverse(), basic]) {
    const slug = c ? OVERTURE_TO_LEAF.get(c) : undefined;
    if (slug) return slug;
  }
  return null;
}

/** First leaf whose OSM rule matches the tags (rules are ordered specific → generic). */
export function osmLeaf(tags: Record<string, string>) {
  for (const l of LEAVES) {
    for (const rule of l.osm) {
      const [k, v] = rule.split('=') as [string, string];
      const tv = tags[k];
      if (tv !== undefined && (v === '*' || tv === v)) return l.slug;
    }
  }
  return null;
}
